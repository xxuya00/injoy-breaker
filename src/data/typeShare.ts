// 그 메모를 접어서 다시 펴 볼 수 있게 해 두었다.
//
// 질문은 자리마다 다섯 개로 끊었다. 검사 자체가 처음인 사람들에게는 질문을 많이 주는 것보다
// 하나를 오래 붙들게 하는 편이 낫고, 다섯 개면 각 단계에 하나씩 돌아간다.

export interface ShareStep {
  /** 지금 무엇을 하는 단계인지 — 진행자가 "여기까지 했다"를 셀 수 있게 이름을 붙였다. */
  title: string;
  /** 입 밖으로 꺼낼 질문 하나. 단계마다 하나씩만 둔다. */
  question: string;
  /** 어떻게 하면 되는지 한 줄. 없으면 질문만 놓인다. */
  note?: string;
}

export interface ShareSession {
  key: 'same' | 'group';
  /** 탭에 걸리는 이름 — 누구와 앉는 자리인지 */
  tab: string;
  /** 이 나눔이 무엇을 하러 모인 자리인지. 질문보다 먼저 읽혀야 한다. */
  purpose: string;
  /** 누구와 어떻게 앉는지 한 줄 */
  lead: string;
  steps: ShareStep[];
  memo: { label: string; placeholder: string };
}

